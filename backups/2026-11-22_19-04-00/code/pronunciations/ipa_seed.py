def get(word):
    """IPA из выверенного словаря (или None). Учитывает артикль в начале."""
    if not word:
        return None
    w = " ".join(str(word).strip().lower().split())
    for art, art_ipa in _ARTICLES.items():
        if w.startswith(art + " "):
            rest = get(w[len(art) + 1:])
            return (art_ipa + " " + rest) if rest else None
    return SEED.get(w)
